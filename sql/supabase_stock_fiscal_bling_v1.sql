  coalesce(variation_id, '')
);

create table if not exists public.inventory_bom_components (
  id bigint generated by default as identity primary key,
  parent_product_id bigint not null references public.inventory_products(id) on delete cascade,
  component_product_id bigint not null references public.inventory_products(id) on delete restrict,
  quantity numeric(14,4) not null check (quantity > 0),
  notes text,
  created_at timestamptz not null default now(),
  unique(parent_product_id, component_product_id)
