create index if not exists idx_inventory_movements_product on public.inventory_movements(product_id, created_at desc);
create index if not exists idx_inventory_movements_order on public.inventory_movements(marketplace_order_id);

create table if not exists public.inventory_reservations (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.inventory_products(id) on delete cascade,
  quantity numeric(14,4) not null check (quantity > 0),
  reference_type text,
  reference_id text,
  status text not null default 'active' check (status in ('active','released','consumed')),
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace view public.inventory_stock as
select
  p.id as product_id,
  p.sku,
  p.name,
  p.category,
  p.product_type,
  p.unit,
  p.minimum_stock,
  p.average_cost,
  p.supplier_name,
  p.location_code,
  p.active,
  coalesce(m.on_hand, 0)::numeric(14,4) as on_hand,
  coalesce(r.reserved, 0)::numeric(14,4) as reserved,
  (coalesce(m.on_hand, 0) - coalesce(r.reserved, 0))::numeric(14,4) as available,
  ((coalesce(m.on_hand, 0) - coalesce(r.reserved, 0)) <= p.minimum_stock) as below_minimum,
  (coalesce(m.on_hand, 0) * p.average_cost)::numeric(14,2) as stock_value
from public.inventory_products p
left join (
  select product_id, sum(quantity) as on_hand
  from public.inventory_movements
  group by product_id
) m on m.product_id = p.id
left join (
  select product_id, sum(quantity) as reserved
  from public.inventory_reservations
  where status = 'active'
  group by product_id
) r on r.product_id = p.id;

