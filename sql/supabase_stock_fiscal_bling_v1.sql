create table if not exists public.inventory_products (
  id bigint generated by default as identity primary key,
  sku text not null unique,
  name text not null,
  description text,
  category text,
  product_type text not null default 'component' check (product_type in ('component','simple','kit','service')),
  unit text not null default 'UN',
  minimum_stock numeric(14,4) not null default 0,
  average_cost numeric(14,4) not null default 0,
  supplier_name text,
  location_code text,
  active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.inventory_marketplace_links (
  id bigint generated by default as identity primary key,
